import { mkdir, writeFile } from 'node:fs/promises'

import { resolvedRules, severity } from './eslint-for.ts'
import { SOURCES, isDeprecated } from './rule-sources.ts'
import type { RuleSource } from './rule-sources.ts'

const OUT_DIR = new URL('../docs/rules/', import.meta.url)

async function writeDoc(source: RuleSource): Promise<void> {
  const rules = await resolvedRules(source.config, source.sample)
  const rows = Object.entries(source.rules)
    .filter(([, rule]) => !isDeprecated(rule))
    .map(([rule, { meta }]) => {
      const id = source.prefix + rule
      const description = (meta?.docs?.description ?? '').replaceAll('|', '\\|')
      return `| \`${id}\` | ${severity(rules[id]) ?? '_undecided_'} | ${description} |`
    })
  const body = [
    `# ${source.name} rules`,
    '',
    'Generated by `pnpm docs:rules`. Deprecated rules are omitted.',
    '',
    '| Rule | Setting | Purpose |',
    '| --- | --- | --- |',
    ...rows,
    '',
  ].join('\n')
  await writeFile(new URL(`${source.name}.md`, OUT_DIR), body)
}

await mkdir(OUT_DIR, { recursive: true })
await Promise.all(SOURCES.map(writeDoc))
